"""Canonical Cosmos Edge observation preparation for LIBERO evaluation."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

import numpy as np
from PIL import Image

EDGE_LIBERO_CAMERAS = ("agentview", "wrist")
EDGE_LIBERO_IMAGE_SIZE = 256
_CAMERA_OBSERVATION_KEYS = {
    "agentview": "agentview_image",
    "wrist": "robot0_eye_in_hand_image",
}


def _as_uint8_rgb(image: Any, name: str) -> np.ndarray:
    array = np.asarray(image)
    if array.ndim != 3 or array.shape[-1] != 3 or array.shape[0] <= 0 or array.shape[1] <= 0:
        raise ValueError(f"{name} must have non-empty HWC RGB shape, got {array.shape}.")
    if array.dtype.kind not in "iuf":
        raise ValueError(f"{name} must contain real numeric pixels, got dtype {array.dtype}.")
    if not np.isfinite(array).all():
        raise ValueError(f"{name} must contain only finite pixels.")

    minimum = float(array.min())
    maximum = float(array.max())
    if minimum < 0.0 or maximum > 255.0:
        raise ValueError(f"{name} pixels must be in [0, 1] or [0, 255], got range [{minimum}, {maximum}].")
    if array.dtype != np.uint8 and maximum <= 1.0:
        array = np.rint(array * 255.0)
    elif array.dtype != np.uint8:
        array = np.rint(array)
    return np.ascontiguousarray(array, dtype=np.uint8)


def _validate_edge_observation_config(
    cameras: Sequence[str],
    image_size: int,
    rotate_180: bool,
    flip_images: bool,
) -> None:
    if tuple(cameras) != EDGE_LIBERO_CAMERAS:
        raise ValueError(f"Cosmos Edge LIBERO requires camera order {EDGE_LIBERO_CAMERAS}, got {tuple(cameras)}.")
    if isinstance(image_size, bool) or not isinstance(image_size, int) or image_size != EDGE_LIBERO_IMAGE_SIZE:
        raise ValueError(f"Cosmos Edge LIBERO requires image_size={EDGE_LIBERO_IMAGE_SIZE}, got {image_size!r}.")
    if rotate_180 is not True:
        raise ValueError("Cosmos Edge LIBERO requires rotate_180=True.")
    if not isinstance(flip_images, bool):
        raise ValueError(f"flip_images must be a boolean, got {flip_images!r}.")


def build_libero_concat_frame(
    observation: Mapping[str, Any],
    *,
    cameras: Sequence[str],
    image_size: int,
    rotate_180: bool,
    flip_images: bool = False,
) -> np.ndarray:
    """Build the canonical ``[3rd-person | wrist]`` 256x512 RGB frame.

    Each camera is rotated by 180 degrees, optionally vertically flipped for
    environments that require the legacy correction, resized independently to
    256x256, and concatenated in the fixed training camera order.
    """
    if not isinstance(observation, Mapping):
        raise ValueError(f"observation must be a mapping, got {type(observation).__name__}.")
    _validate_edge_observation_config(cameras, image_size, rotate_180, flip_images)

    views: list[np.ndarray] = []
    for camera in EDGE_LIBERO_CAMERAS:
        observation_key = _CAMERA_OBSERVATION_KEYS[camera]
        if observation_key not in observation:
            raise ValueError(f"observation is missing required camera key {observation_key!r}.")
        image = _as_uint8_rgb(observation[observation_key], observation_key)
        image = image[::-1, ::-1]
        if flip_images:
            image = np.flipud(image)

        pil_image = Image.fromarray(np.ascontiguousarray(image), mode="RGB")
        if pil_image.size != (EDGE_LIBERO_IMAGE_SIZE, EDGE_LIBERO_IMAGE_SIZE):
            pil_image = pil_image.resize(
                (EDGE_LIBERO_IMAGE_SIZE, EDGE_LIBERO_IMAGE_SIZE),
                resample=Image.Resampling.BILINEAR,
            )
        views.append(np.asarray(pil_image, dtype=np.uint8).copy())

    return np.ascontiguousarray(np.concatenate(views, axis=1), dtype=np.uint8)


def build_wam_conditioning_video(current_concat_frame: np.ndarray, action_chunk_size: int) -> np.ndarray:
    """Repeat the current frame into the WAM ``[C, T, H, W]`` shape template.

    ``T`` is ``action_chunk_size + 1``. All temporal slices contain the current
    observation, but only temporal index 0 is clean conditioning in the WAM
    sequence plan; indexes 1..T-1 are placeholders that will be noised and
    generated by the model.
    """
    if isinstance(action_chunk_size, bool) or not isinstance(action_chunk_size, int) or action_chunk_size <= 0:
        raise ValueError(f"action_chunk_size must be a positive integer, got {action_chunk_size!r}.")
    frame = np.asarray(current_concat_frame)
    expected_shape = (EDGE_LIBERO_IMAGE_SIZE, EDGE_LIBERO_IMAGE_SIZE * len(EDGE_LIBERO_CAMERAS), 3)
    if frame.shape != expected_shape:
        raise ValueError(f"current_concat_frame must have shape {expected_shape}, got {frame.shape}.")
    if frame.dtype != np.uint8:
        raise ValueError(f"current_concat_frame must have dtype uint8, got {frame.dtype}.")

    video_t_h_w_c = np.repeat(np.ascontiguousarray(frame)[None, ...], action_chunk_size + 1, axis=0)
    return np.ascontiguousarray(video_t_h_w_c.transpose(3, 0, 1, 2))
